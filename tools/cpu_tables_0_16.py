#!/usr/bin/env python3
"""Writes src/cpu_tables_0_16.zig: Zig 0.16's CPU features and models for
the architectures bs targets (x86_64 and aarch64), which a Zig 0.16
compilation's builtin module names (`cpu016.resolve`). 0.17 renamed, added
and dropped features and models, so bs's own std (0.17.1) cannot name them.

The tables come from zig 0.16.0 itself: a small program compiled with it
prints `std.Target.<arch>.all_features` (each feature's name and
dependencies) and every `std.Target.<arch>.cpu` model (its name and
features), in the order 0.16 lists them. Run from the repository root:

    python3 tools/cpu_tables_0_16.py [--zig-0.16 ZIG] [--check]

The zig defaults to ~/.cache/bs/zig-<host>-0.16.0/zig. With --check, the
file is compared, not written, and a difference fails.
"""

import argparse
import os
import platform
import subprocess
import sys
import tempfile

OUT = os.path.join("src", "cpu_tables_0_16.zig")

# (the declaration in the output, std.Target's namespace, the Cpu.Arch)
ARCHES = [("x86", "x86", "x86_64"), ("aarch64", "aarch64", "aarch64")]

DUMP = """
const std = @import("std");

pub fn main(init: std.process.Init) !void {
    var buf: [1 << 16]u8 = undefined;
    var w = std.Io.File.stdout().writer(init.io, &buf);
    const out = &w.interface;
    inline for (.{ ARCHES }) |pair| {
        const ns = @field(std.Target, pair[0]);
        const arch: std.Target.Cpu.Arch = @field(std.Target.Cpu.Arch, pair[1]);
        const all = arch.allFeaturesList();
        try out.print("arch {s}\\n", .{pair[0]});
        for (all, 0..) |f, i| {
            try out.print("feature {s}", .{f.name});
            for (all, 0..) |_, j| if (f.dependencies.isEnabled(@intCast(j))) try out.print(" {d}", .{j});
            _ = i;
            try out.writeAll("\\n");
        }
        inline for (@typeInfo(ns.cpu).@"struct".decls) |d| {
            const m: *const std.Target.Cpu.Model = &@field(ns.cpu, d.name);
            try out.print("model {s}", .{m.name});
            for (all, 0..) |_, j| if (m.features.isEnabled(@intCast(j))) try out.print(" {d}", .{j});
            try out.writeAll("\\n");
        }
    }
    try out.flush();
}
"""


def dump(zig: str) -> dict:
    got = subprocess.run([zig, "version"], check=True, capture_output=True, text=True).stdout.strip()
    if got != "0.16.0":
        sys.exit(f"{zig} is zig {got}, not 0.16.0")
    pairs = ", ".join(f'.{{ "{ns}", "{arch}" }}' for _, ns, arch in ARCHES)
    with tempfile.TemporaryDirectory() as tmp:
        src = os.path.join(tmp, "dump.zig")
        with open(src, "w") as f:
            f.write(DUMP.replace("ARCHES", pairs))
        out = subprocess.run(
            [zig, "run", src, "--cache-dir", os.path.join(tmp, "cache")], check=True, capture_output=True, text=True
        ).stdout
    tables = {}
    cur = None
    for line in out.splitlines():
        kind, name, *rest = line.split(" ")
        if kind == "arch":
            cur = tables[name] = {"features": [], "models": []}
        else:
            cur["features" if kind == "feature" else "models"].append((name, [int(x) for x in rest]))
    return tables


def ints(xs: list) -> str:
    """A `&.{ ... }` as zig fmt writes it."""
    if len(xs) < 2:
        return "&.{" + "".join(map(str, xs)) + "}"
    return "&.{ " + ", ".join(map(str, xs)) + " }"


def render(tables: dict) -> str:
    lines = [
        "//! Generated by tools/cpu_tables_0_16.py from zig 0.16.0's std.Target:",
        "//! for each architecture bs targets, every feature (its name and the",
        "//! indices of the features it depends on) and every CPU model (its name",
        "//! and the indices of its features), in 0.16's order. Do not edit.",
        "",
        "pub const Feature = struct { name: []const u8, deps: []const u16 };",
        "pub const Model = struct { name: []const u8, features: []const u16 };",
        "pub const Arch = struct { features: []const Feature, models: []const Model };",
    ]
    for decl, ns, _ in ARCHES:
        t = tables[ns]
        lines.append("")
        lines.append(f"pub const {decl}: Arch = .{{")
        lines.append("    .features = &.{")
        for name, deps in t["features"]:
            lines.append(f'        .{{ .name = "{name}", .deps = {ints(deps)} }},')
        lines.append("    },")
        lines.append("    .models = &.{")
        for name, feats in t["models"]:
            lines.append(f'        .{{ .name = "{name}", .features = {ints(feats)} }},')
        lines.append("    },")
        lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> None:
    host = f"{platform.machine().lower().replace('arm64', 'aarch64')}-{platform.system().lower().replace('darwin', 'macos')}"
    p = argparse.ArgumentParser()
    p.add_argument("--zig-0.16", dest="zig_0_16", default=os.path.expanduser(f"~/.cache/bs/zig-{host}-0.16.0/zig"))
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    tables = dump(args.zig_0_16)
    text = render(tables)
    if args.check:
        with open(OUT) as f:
            if f.read() != text:
                sys.exit(f"{OUT} is out of date: run python3 tools/cpu_tables_0_16.py")
        return
    with open(OUT, "w") as f:
        f.write(text)
    print(
        ", ".join(
            f"{decl}: {len(tables[ns]['features'])} features, {len(tables[ns]['models'])} models"
            for decl, ns, _ in ARCHES
        )
    )


if __name__ == "__main__":
    main()
