#!/usr/bin/env python3
"""Writes src/upstream_lists.zig: the lists bs copies from upstream's
compiler sources that differ between the Zig languages bs compiles, one per
language, each from its release's source tree:

- musl's libc.a sources (`src_files` in src/libs/musl.zig, `Musl.sources`);
- the LLVM feature names of x86 and aarch64 (lib/std/Target/<arch>.zig),
  which CSource passes to a language's Clang. 0.17's are bs's own
  std.Target's, so only older languages get a list.

The lists that are the same in every language (libc++'s, libc++abi's and
libunwind's sources) stay in CSource.zig; the script fails if they differ
between the trees.
Run from the repository root:

    python3 tools/upstream_lists.py [--src-0.17 DIR] [--src-0.16 DIR] [--check]

The source trees default to upstream/ and upstream-0.16/, which
.agents/setup links.
"""

import argparse
import os
import re
import sys

OUT = os.path.join("src", "upstream_lists.zig")


def list_decl(path: str, name: str) -> list:
    with open(path) as f:
        text = f.read()
    m = re.search(r"\nconst " + re.escape(name) + r" = \[_\]\[\]const u8\{(.*?)\n\};", text, re.DOTALL)
    if not m:
        sys.exit(f"{path}: no `{name}` list")
    return re.findall(r'"([^"]+)"', m.group(1))


def llvm_features(src: str, arch: str) -> list:
    with open(os.path.join(src, "lib", "std", "Target", f"{arch}.zig")) as f:
        features_part = f.read().partition("pub const cpu = struct")[0]
    return sorted(set(re.findall(r'\.llvm_name = "([^"]+)"', features_part)))


def zig_list(name: str, items: list) -> list:
    lines = [f"pub const {name} = [_][]const u8{{"]
    lines += [f'    "{i}",' for i in items]
    lines.append("};")
    return lines


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--src-0.17", dest="src_0_17", default="upstream")
    p.add_argument("--src-0.16", dest="src_0_16", default="upstream-0.16")
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    trees = {"zig_0_17": args.src_0_17, "zig_0_16": args.src_0_16}

    # The lists CSource.zig keeps once, for every language.
    shared = [
        ("libcxx.zig", "libcxx_base_files"),
        ("libcxx.zig", "libcxx_thread_files"),
        ("libcxx.zig", "libcxxabi_files"),
        ("libunwind.zig", "unwind_src_list"),
    ]
    for file, name in shared:
        lists = {lang: list_decl(os.path.join(src, "src", "libs", file), name) for lang, src in trees.items()}
        if lists["zig_0_17"] != lists["zig_0_16"]:
            sys.exit(f"{file}'s {name} differs between the languages: CSource.zig needs one per language")

    lines = [
        "//! Generated by tools/upstream_lists.py from each Zig language's",
        "//! upstream source tree: the lists bs copies from upstream that differ",
        "//! between the languages. Do not edit.",
    ]
    for lang, src in trees.items():
        lines.append("")
        lines.append(f"/// musl's libc.a sources in upstream's order, as {lang}'s src/libs/musl.zig")
        lines.append("/// lists them (`Musl.sources`).")
        lines += zig_list(
            f"musl_src_files_{lang[4:]}", list_decl(os.path.join(src, "src", "libs", "musl.zig"), "src_files")
        )
    for arch in ("x86", "aarch64"):
        lines.append("")
        lines.append(f"/// The LLVM feature names of 0.16's std.Target.{arch}, which its Clang knows.")
        lines += zig_list(f"llvm_features_0_16_{arch}", llvm_features(trees["zig_0_16"], arch))
    text = "\n".join(lines) + "\n"
    if args.check:
        with open(OUT) as f:
            if f.read() != text:
                sys.exit(f"{OUT} is out of date: run python3 tools/upstream_lists.py")
        return
    with open(OUT, "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
