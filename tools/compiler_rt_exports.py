#!/usr/bin/env python3
"""Writes src/compiler_rt_exports.zig: for each Zig language bs compiles,
the functions and variables upstream's compiler_rt exports for
x86_64-linux, each with the file and declaration that implement it
(`Zcu.compilerRtExport`).

Upstream compiles lib/compiler_rt.zig for the target, in Debug, which keeps
each declaration's own symbol (`compiler_rt.<file>.<decl>`, with nested
containers' names in `<decl>`) at the address of the names it exports, so
the table follows upstream's conditions exactly. Each language's table
comes from its own release's zig and lib directory.
Run from the repository root:

    python3 tools/compiler_rt_exports.py [--zig-0.17 ZIG] [--zig-0.16 ZIG] [--check]

The zigs default to `zig` on PATH (0.17.1) and
~/.cache/bs/zig-<host>-0.16.0/zig. With --check, the file is compared, not
written, and a difference fails.
"""

import argparse
import collections
import os
import platform
import re
import subprocess
import sys
import tempfile

OUT = os.path.join("src", "compiler_rt_exports.zig")

# Stack protector functions: the compilation roots compiler_rt/ssp.zig
# when it links C objects (`Zcu.rootFiles`), so they are its own exports.
SKIP_FILES = {"ssp.zig"}

# (declaration in the output, version `zig version` must print)
LANGUAGES = [("zig_0_17", "0.17.1"), ("zig_0_16", "0.16.0")]


def lib_dir(zig: str, version: str) -> str:
    got = subprocess.run([zig, "version"], check=True, capture_output=True, text=True).stdout.strip()
    if got != version:
        sys.exit(f"{zig} is zig {got}, not {version}")
    env = subprocess.run([zig, "env"], check=True, capture_output=True, text=True).stdout
    m = re.search(r'\.lib_dir = "([^"]*)"', env)
    if not m:
        sys.exit(f"{zig} env names no lib_dir")
    return m.group(1)


def table(zig: str, version: str) -> list:
    src = os.path.join(lib_dir(zig, version), "compiler_rt.zig")
    with tempfile.TemporaryDirectory() as tmp:
        obj = os.path.join(tmp, "crt.o")
        subprocess.run(
            [zig, "build-obj", "-target", "x86_64-linux-gnu", "-ODebug", "--name", "crt", f"-femit-bin={obj}", src],
            check=True,
        )
        out = subprocess.run(["readelf", "-sW", obj], check=True, capture_output=True, text=True).stdout
    # Functions and variables, by section and address: an export and the
    # local symbol of the declaration that implements it share both.
    by_addr = collections.defaultdict(list)
    exports = []
    for line in out.splitlines():
        parts = line.split()
        if len(parts) != 8 or parts[3] not in ("FUNC", "OBJECT") or not parts[6].isdigit():
            continue
        addr, bind, ndx, name = parts[1], parts[4], parts[6], parts[7]
        if bind in ("GLOBAL", "WEAK"):
            exports.append((name, ndx, addr))
        elif bind == "LOCAL" and name.startswith("compiler_rt."):
            by_addr[ndx, addr].append(name[len("compiler_rt.") :])
    rows = []
    for name, ndx, addr in sorted(exports):
        impl = by_addr.get((ndx, addr), [])
        if len(impl) != 1:
            sys.exit(f"zig {version}: {name}: expected one implementing declaration, found {impl}")
        path = impl[0].split(".")
        if len(path) == 1:
            file, decl = "", path[0]
        else:
            file, decl = path[0] + ".zig", ".".join(path[1:])
        if file not in SKIP_FILES:
            rows.append((name, file, decl))
    return rows


def render(tables: dict) -> str:
    lines = [
        "//! Generated by tools/compiler_rt_exports.py from upstream's compiler_rt",
        "//! for x86_64-linux, one table per Zig language, each from its release's",
        "//! lib directory: each exported function's or variable's name, then the",
        "//! file under lib/compiler_rt/ (empty: lib/compiler_rt.zig) and the",
        "//! declaration that implement it, with nested containers' names in it.",
        "//! aarch64-macos exports the same functions except `__gnu_h2f_ieee`,",
        "//! `__gnu_f2h_ieee` and `__zig_probe_stack`, plus",
        "//! `__isPlatformVersionAtLeast`, and fmv.zig's `aarch64` declarations",
        "//! instead of its `x86` ones. Do not edit.",
        "",
        "pub const Export = struct { []const u8, []const u8, []const u8 };",
    ]
    for decl, version in LANGUAGES:
        lines.append("")
        lines.append(f"/// zig {version}'s.")
        lines.append(f"pub const {decl} = [_]Export{{")
        for name, file, d in tables[decl]:
            lines.append(f'    .{{ "{name}", "{file}", "{d}" }},')
        lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> None:
    host = f"{platform.machine().lower().replace('arm64', 'aarch64')}-{platform.system().lower().replace('darwin', 'macos')}"
    p = argparse.ArgumentParser()
    p.add_argument("--zig-0.17", dest="zig_0_17", default="zig")
    p.add_argument("--zig-0.16", dest="zig_0_16", default=os.path.expanduser(f"~/.cache/bs/zig-{host}-0.16.0/zig"))
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    tables = {decl: table(getattr(args, decl), version) for decl, version in LANGUAGES}
    text = render(tables)
    if args.check:
        with open(OUT) as f:
            if f.read() != text:
                sys.exit(f"{OUT} is out of date: run python3 tools/compiler_rt_exports.py")
        return
    with open(OUT, "w") as f:
        f.write(text)
    print(", ".join(f"{decl}: {len(tables[decl])} exports" for decl, _ in LANGUAGES))


if __name__ == "__main__":
    main()
