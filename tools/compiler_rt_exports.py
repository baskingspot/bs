#!/usr/bin/env python3
"""Writes src/compiler_rt_exports.zig: the functions upstream's compiler_rt
exports for x86_64-linux, each with the file and declaration that implement
it (`Zcu.compilerRtExport`).

Upstream compiles lib/compiler_rt.zig for the target, in Debug, which keeps
each function's own symbol (`compiler_rt.<file>.<decl>`) at the address of
the names it exports, so the table follows upstream's conditions exactly.
Run from the repository root with upstream `zig` 0.17.1 on PATH:

    python3 tools/compiler_rt_exports.py
"""

import collections
import os
import subprocess
import sys
import tempfile

# Stack protector functions: the compilation roots compiler_rt/ssp.zig
# when it links C objects (`Zcu.rootFiles`), so they are its own exports.
SKIP_FILES = {"ssp.zig"}
# Function multiversioning stubs (0.17.1's fmv.zig): `__cpu_indicator_init`
# is declared in a nested struct, next to the data `__cpu_model` and
# `__cpu_features2`, which this table cannot name. Not provided yet.
SKIP_NESTED = {"fmv.x86.__cpu_indicator_init"}


def main() -> None:
    src = os.path.join("upstream", "lib", "compiler_rt.zig")
    with tempfile.TemporaryDirectory() as tmp:
        obj = os.path.join(tmp, "crt.o")
        subprocess.run(
            ["zig", "build-obj", "-target", "x86_64-linux-gnu", "-ODebug", "--name", "crt",
             f"-femit-bin={obj}", src],
            check=True,
        )
        out = subprocess.run(["nm", obj], check=True, capture_output=True, text=True).stdout
    by_addr = collections.defaultdict(list)
    exports = []
    for line in out.splitlines():
        parts = line.split()
        if len(parts) != 3:
            continue
        addr, kind, name = parts
        if kind in "WT":
            exports.append((name, addr))
        elif kind == "t" and name.startswith("compiler_rt."):
            by_addr[addr].append(name[len("compiler_rt."):])
    rows = []
    for name, addr in sorted(exports):
        impl = by_addr.get(addr, [])
        if len(impl) != 1:
            sys.exit(f"{name}: expected one implementing function, found {impl}")
        path = impl[0].split(".")
        if len(path) == 1:
            file, decl = "", path[0]
        elif len(path) == 2:
            file, decl = path[0] + ".zig", path[1]
        elif impl[0] in SKIP_NESTED:
            continue
        else:
            sys.exit(f"{name}: implemented by a nested declaration ({impl[0]})")
        if file not in SKIP_FILES:
            rows.append((name, file, decl))
    with open(os.path.join("src", "compiler_rt_exports.zig"), "w") as f:
        f.write("//! Generated by tools/compiler_rt_exports.py from upstream's compiler_rt\n")
        f.write("//! for x86_64-linux: each exported name, then the file under\n")
        f.write("//! lib/compiler_rt/ (empty: lib/compiler_rt.zig) and the declaration\n")
        f.write("//! that implement it. aarch64-macos exports the same functions except\n")
        f.write("//! `__gnu_h2f_ieee`, `__gnu_f2h_ieee` and `__zig_probe_stack`, plus\n")
        f.write("//! `__isPlatformVersionAtLeast`. Do not edit.\n\n")
        f.write("pub const exports = [_]struct { []const u8, []const u8, []const u8 }{\n")
        for name, file, decl in rows:
            f.write(f'    .{{ "{name}", "{file}", "{decl}" }},\n')
        f.write("};\n")
    print(f"{len(rows)} exports")


if __name__ == "__main__":
    main()
