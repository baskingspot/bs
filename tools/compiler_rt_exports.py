#!/usr/bin/env python3
"""Writes src/compiler_rt_exports.zig: the functions and variables upstream's
compiler_rt exports for x86_64-linux, each with the file and declaration
that implement it (`Zcu.compilerRtExport`).

Upstream compiles lib/compiler_rt.zig for the target, in Debug, which keeps
each declaration's own symbol (`compiler_rt.<file>.<decl>`, with nested
containers' names in `<decl>`) at the address of the names it exports, so
the table follows upstream's conditions exactly.
Run from the repository root with upstream `zig` 0.17.1 on PATH:

    python3 tools/compiler_rt_exports.py
"""

import collections
import os
import subprocess
import sys
import tempfile

# Stack protector functions: the compilation roots compiler_rt/ssp.zig
# when it links C objects (`Zcu.rootFiles`), so they are its own exports.
SKIP_FILES = {"ssp.zig"}


def main() -> None:
    src = os.path.join("upstream", "lib", "compiler_rt.zig")
    with tempfile.TemporaryDirectory() as tmp:
        obj = os.path.join(tmp, "crt.o")
        subprocess.run(
            ["zig", "build-obj", "-target", "x86_64-linux-gnu", "-ODebug", "--name", "crt",
             f"-femit-bin={obj}", src],
            check=True,
        )
        out = subprocess.run(["readelf", "-sW", obj], check=True, capture_output=True, text=True).stdout
    # Functions and variables, by section and address: an export and the
    # local symbol of the declaration that implements it share both.
    by_addr = collections.defaultdict(list)
    exports = []
    for line in out.splitlines():
        parts = line.split()
        if len(parts) != 8 or parts[3] not in ("FUNC", "OBJECT") or not parts[6].isdigit():
            continue
        addr, bind, ndx, name = parts[1], parts[4], parts[6], parts[7]
        if bind in ("GLOBAL", "WEAK"):
            exports.append((name, ndx, addr))
        elif bind == "LOCAL" and name.startswith("compiler_rt."):
            by_addr[ndx, addr].append(name[len("compiler_rt."):])
    rows = []
    for name, ndx, addr in sorted(exports):
        impl = by_addr.get((ndx, addr), [])
        if len(impl) != 1:
            sys.exit(f"{name}: expected one implementing declaration, found {impl}")
        path = impl[0].split(".")
        if len(path) == 1:
            file, decl = "", path[0]
        else:
            file, decl = path[0] + ".zig", ".".join(path[1:])
        if file not in SKIP_FILES:
            rows.append((name, file, decl))
    with open(os.path.join("src", "compiler_rt_exports.zig"), "w") as f:
        f.write("//! Generated by tools/compiler_rt_exports.py from upstream's compiler_rt\n")
        f.write("//! for x86_64-linux: each exported function's or variable's name, then\n")
        f.write("//! the file under lib/compiler_rt/ (empty: lib/compiler_rt.zig) and the\n")
        f.write("//! declaration that implement it, with nested containers' names in it.\n")
        f.write("//! aarch64-macos exports the same functions except `__gnu_h2f_ieee`,\n")
        f.write("//! `__gnu_f2h_ieee` and `__zig_probe_stack`, plus\n")
        f.write("//! `__isPlatformVersionAtLeast`, and fmv.zig's `aarch64` declarations\n")
        f.write("//! instead of its `x86` ones. Do not edit.\n\n")
        f.write("pub const exports = [_]struct { []const u8, []const u8, []const u8 }{\n")
        for name, file, decl in rows:
            f.write(f'    .{{ "{name}", "{file}", "{decl}" }},\n')
        f.write("};\n")
    print(f"{len(rows)} exports")


if __name__ == "__main__":
    main()
