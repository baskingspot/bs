//! `zap build`: compiles upstream's build runner (`lib/compiler/Maker.zig`)
//! with zap and replaces zap with it, as upstream's `zig build` does, but
//! with `--zig=<zap>`: the runner then compiles `build.zig` (with
//! `lib/compiler/configurer.zig`) and every compile step by running zap
//! with `--listen=-` (`main.serve`).
//!
//! Upstream compiles the runner once per global cache in ReleaseSafe with
//! LLVM (75 s on the bench orb); zap compiles it in Debug, once per zap
//! binary and zig lib directory, into `<global cache>/zap/o/<hash>/maker`,
//! and a build with nothing changed reuses it without relinking.

const std = @import("std");
const Io = std.Io;
const build_options = @import("build_options");
const main = @import("main.zig");
const cache = @import("cache.zig");
const Frontend = @import("Frontend.zig");
const Incremental = @import("Incremental.zig");

/// The runner's root module. Upstream builds the runner in ReleaseSafe,
/// whose default log level is info; zap builds only Debug, whose default
/// is debug, so the runner's own `std_options` would print its debug logs
/// (`configuration cache incomplete_manifest`). Otherwise the same options.
const root_source =
    \\//! Generated by zap: upstream's build runner with upstream's log level.
    \\const maker = @import("maker");
    \\pub const main = maker.main;
    \\pub const std_options: @import("std").Options = .{
    \\    .side_channels_mitigations = maker.std_options.side_channels_mitigations,
    \\    .log_level = .info,
    \\};
    \\
;

pub fn run(init: std.process.Init, args: []const []const u8) !void {
    const arena = init.arena.allocator();
    const io = init.io;
    const env = init.environ_map;
    var user_args = args;
    // As upstream, `--zig-lib=` is only recognized first.
    var lib_override: ?[]const u8 = null;
    if (user_args.len != 0 and std.mem.startsWith(u8, user_args[0], "--zig-lib=")) {
        lib_override = user_args[0]["--zig-lib=".len..];
        user_args = user_args[1..];
    }
    const cwd = try std.process.currentPathAlloc(io, arena);
    const zig_lib_dir = try std.fs.path.resolve(arena, &.{ cwd, lib_override orelse env.get("ZIG_LIB_DIR") orelse build_options.zig_lib_dir });
    const dirs = Frontend.resolveCacheDirs(arena, io, env, .{ .local_is_global = true });
    const global = try std.fs.path.resolve(arena, &.{ cwd, dirs.global });

    // One runner per zap binary and zig lib directory.
    const seed, _ = try Incremental.compilationKey(arena, io, &.{}, zig_lib_dir, "x86_64-linux");
    const runner_hash = cache.hash(2, try std.mem.concat(arena, u8, &.{ std.mem.asBytes(&seed), zig_lib_dir }));
    const runner_dir = try std.fmt.allocPrint(arena, "{s}/zap/o/{x:0>32}", .{ global, runner_hash });
    try Io.Dir.cwd().createDirPath(io, runner_dir);
    const runner_path = try std.fs.path.join(arena, &.{ runner_dir, "maker" });
    // With zap's own zig lib directory, the pinned release's, which nobody
    // edits, a runner that is as the last check left it is current: that
    // saves the check's stat of every source the runner imports (about
    // 3 ms of a 38 ms no-change build). A lib directory given with
    // `--zig-lib=` or ZIG_LIB_DIR may be a source tree under edit, so it
    // is always checked.
    const stamp_path = try std.fs.path.join(arena, &.{ runner_dir, "maker.stat" });
    const trusted_lib = lib_override == null and env.get("ZIG_LIB_DIR") == null;
    if (!(trusted_lib and toolUnchanged(io, runner_path, stamp_path))) {
        const root_path = try std.fs.path.join(arena, &.{ runner_dir, "root.zig" });
        const same = if (Io.Dir.cwd().readFileAlloc(io, root_path, arena, .limited(4096))) |old| std.mem.eql(u8, old, root_source) else |_| false;
        if (!same) {
            var atomic = try Io.Dir.cwd().createFileAtomic(io, root_path, .{ .replace = true });
            defer atomic.deinit(io);
            try atomic.file.writeStreamingAll(io, root_source);
            try atomic.replace(io);
        }
        try compileTool(init, runner_dir, &.{
            "zap",           "build-exe",
            "--dep",         "maker",
            "-Mroot=root.zig", try std.fmt.allocPrint(arena, "-Mmaker={s}/compiler/Maker.zig", .{zig_lib_dir}),
            "--name",        "maker",
            "--zig-lib-dir", zig_lib_dir,
            "--cache-dir",   global,
            "--global-cache-dir", global,
        }, "Compiling build runner", "build runner", try std.fmt.allocPrint(arena, "{s}/compiler/Maker.zig", .{zig_lib_dir}), null);
        noteTool(io, runner_path, stamp_path);
    }

    const self_exe = try std.process.executablePathAlloc(io, arena);
    var seed_bytes: [4]u8 = undefined;
    io.random(&seed_bytes);
    var argv: std.ArrayList([]const u8) = .empty;
    try argv.appendSlice(arena, &.{
        runner_path,
        "build",
        try std.fmt.allocPrint(arena, "--zig-lib={s}", .{zig_lib_dir}),
        try std.fmt.allocPrint(arena, "--zig={s}", .{self_exe}),
        try std.fmt.allocPrint(arena, "--global-cache={s}", .{global}),
        try std.fmt.allocPrint(arena, "--seed=0x{x}", .{std.mem.readInt(u32, &seed_bytes, .little)}),
    });
    try argv.appendSlice(arena, user_args);
    if (env.get("ZIG_VERBOSE_CMD") != null) std.log.info("{f}", .{std.zig.SubprocessCommand{ .argv = argv.items }});
    const err = std.process.replace(io, .{ .argv = argv.items, .environ_map = env });
    main.fatal("the following command failed to execve with '{t}':\n{s}", .{ err, try std.mem.join(arena, " ", argv.items) });
}

/// Compiles one of upstream's programs that zap runs (the build runner,
/// translate-c) with `compile_args`, from `dir`, where its binary goes.
/// `root_dir` is the root module's directory if not the root file's.
pub fn compileTool(init: std.process.Init, dir: []const u8, compile_args: []const []const u8, progress: []const u8, what: []const u8, root: []const u8, root_dir: ?[]const u8) !void {
    const arena = init.arena.allocator();
    const io = init.io;
    const cwd = try std.process.currentPathAlloc(io, arena);
    // Compiled from its own directory, so that the compilation's key (which
    // includes the working directory) is the same for every project.
    try std.process.setCurrentPath(io, dir);
    var opts = try main.parseOptions(arena, io, init.environ_map, .build_exe, compile_args[2..]);
    opts.root_dir = root_dir;
    const job: main.Job = try .init(init, compile_args, opts);
    {
        const prog = std.Progress.start(io, .{ .root_name = progress });
        defer prog.end();
        var inc = job.openCache(job.stem);
        defer if (inc) |*i| i.close();
        switch (try main.compile(init, &job, if (inc) |*i| i else null, job.stem, prog, null)) {
            .ok => {},
            .errors => |diags| {
                main.printDiagnostics(io, diags, .text) catch {};
                main.fatal("zap could not compile the {s} ({s})", .{ what, root });
            },
            .failed => main.fatal("zap could not link the {s} ({s})", .{ what, root }),
        }
    }
    try std.process.setCurrentPath(io, cwd);
}

/// A tool's stat, as `noteTool` recorded it after the last check.
const RunnerStat = extern struct { inode: u64, size: u64, mtime: i64 };

fn runnerStat(io: Io, path: []const u8) ?RunnerStat {
    const st = Io.Dir.cwd().statFile(io, path, .{}) catch return null;
    return .{ .inode = @intCast(st.inode), .size = st.size, .mtime = @intCast(st.mtime.toNanoseconds()) };
}

pub fn toolUnchanged(io: Io, runner_path: []const u8, stamp_path: []const u8) bool {
    var buf: [@sizeOf(RunnerStat)]u8 = undefined;
    const bytes = Io.Dir.cwd().readFile(io, stamp_path, &buf) catch return false;
    if (bytes.len != buf.len) return false;
    const now = runnerStat(io, runner_path) orelse return false;
    return std.mem.eql(u8, std.mem.asBytes(&now), bytes);
}

/// Records the stat of a tool that was just checked. Best effort.
pub fn noteTool(io: Io, runner_path: []const u8, stamp_path: []const u8) void {
    const st = runnerStat(io, runner_path) orelse return;
    var atomic = Io.Dir.cwd().createFileAtomic(io, stamp_path, .{ .replace = true }) catch return;
    defer atomic.deinit(io);
    atomic.file.writeStreamingAll(io, std.mem.asBytes(&st)) catch return;
    atomic.replace(io) catch {};
}
